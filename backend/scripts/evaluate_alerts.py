"""Evaluate the alert engine on synthetic patients with KNOWN injected deterioration (check 22).

Replays every patient day by day (as if the engine ran each evening) from day 112
(the first day a full 4-week + 12-week history exists) to the end of the data.

  rising patients          seizure rate x3 from a hidden onset day
                           -> flagged if a `seizure_increase` alert fires on/after onset
  poor_adherence patients  adherence drops from a hidden onset day
                           -> flagged if an `adherence_drop` alert fires on/after onset
  stable patients          no injected change
                           -> false alarm if either alert type fires at any time in the window

Writes reports/alert_evaluation.md. Run: python -m scripts.evaluate_alerts
"""
from datetime import timedelta
from pathlib import Path
from statistics import median

from engine.alerts import evaluate
from nawba.settings import rules
from scripts.synthetic import DAYS, DEFAULT_END, generate

REPORT = Path(__file__).resolve().parents[1] / "reports" / "alert_evaluation.md"
FIRST_DAY = 112


def first_flag(data, pid, alert_type, from_day, cfg, start, meds, by):
    for day in range(from_day, DAYS):
        now = start + timedelta(days=day, hours=21)
        alerts = evaluate({"id": pid, "pregnant": False}, by["seizures"][pid], by["intakes"][pid],
                          by["reports"][pid], meds[pid], now, cfg)
        if any(a["type"] == alert_type for a in alerts):
            return day
    return None


def main():
    data, cfg = generate(), rules()
    start = DEFAULT_END - timedelta(days=DAYS)
    by = {k: {p["id"]: [] for p in data["patients"]} for k in ("seizures", "intakes", "reports")}
    for k in by:
        for x in data[k]:
            by[k][x["patient_id"]].append(x)
    meds = {m["patient_id"]: [{"id": 1, **m}] for m in data["medications"]}
    truth = data["truth"]

    lines = ["# Alert engine evaluation (generated by `python -m scripts.evaluate_alerts`)", "",
             f"Synthetic data, seed 42, {len(truth)} patients, {DAYS} days. Engine replayed daily from day {FIRST_DAY}. "
             f"Rules version {cfg['version']}. Numbers are measured, not edited.", ""]
    for archetype, alert_type in (("rising", "seizure_increase"), ("poor_adherence", "adherence_drop")):
        cases = [pid for pid, t in truth.items() if t["archetype"] == archetype]
        delays, missed = [], []
        for pid in cases:
            onset = truth[pid]["onset_day"]
            day = first_flag(data, pid, alert_type, max(onset, FIRST_DAY), cfg, start, meds, by)
            if day is None:
                missed.append(pid)
            else:
                delays.append(day - onset)
        stable = [pid for pid, t in truth.items() if t["archetype"] == "stable"]
        false_alarms = [pid for pid in stable if first_flag(data, pid, alert_type, FIRST_DAY, cfg, start, meds, by) is not None]
        sens = len(delays) / len(cases)
        lines += [f"## {alert_type} on `{archetype}` patients", "",
                  "| metric | value |", "|---|---|",
                  f"| injected cases | {len(cases)} |",
                  f"| flagged after onset (sensitivity) | {len(delays)}/{len(cases)} = {sens:.3f} |",
                  f"| median days from onset to first flag | {median(delays) if delays else 'n/a'} |",
                  f"| range of days to flag | {min(delays) if delays else 'n/a'}–{max(delays) if delays else 'n/a'} |",
                  f"| stable patients wrongly flagged (false alarm rate) | {len(false_alarms)}/{len(stable)} = {len(false_alarms) / len(stable):.3f} |",
                  ""]
        if missed:
            lines.append(f"Not flagged: {', '.join(missed)} (onset day(s) {', '.join(str(truth[p]['onset_day']) for p in missed)}).")
            lines.append("")
    # Trade-off table for the clinician. Same synthetic data as above: an EXPLORATION, not a tuned result.
    lines += ["## Trend threshold trade-off (exploration on the same data — for the neurologist to decide)", "",
              "| max_p_value | min_recent_count | sensitivity (rising) | median days to flag | false alarm rate (stable) |",
              "|---|---|---|---|---|"]
    rising = [pid for pid, t in truth.items() if t["archetype"] == "rising"]
    stable = [pid for pid, t in truth.items() if t["archetype"] == "stable"]
    for ratio, count in ((0.05, 3), (0.01, 3), (0.01, 4), (0.001, 3)):
        c = {**cfg, "trend": {**cfg["trend"], "max_p_value": ratio, "min_recent_count": count}}
        d = [first_flag(data, p, "seizure_increase", max(truth[p]["onset_day"], FIRST_DAY), c, start, meds, by) for p in rising]
        delays = [x - truth[p]["onset_day"] for x, p in zip(d, rising) if x is not None]
        fa = sum(first_flag(data, p, "seizure_increase", FIRST_DAY, c, start, meds, by) is not None for p in stable)
        mark = " (config default)" if (ratio, count) == (cfg["trend"]["max_p_value"], cfg["trend"]["min_recent_count"]) else ""
        lines.append(f"| {ratio}{mark} | {count} | {len(delays)}/{len(rising)} | {median(delays) if delays else 'n/a'} | {fa}/{len(stable)} |")
    lines += [""]
    # Snapshot: what the clinician queue shows on the last day (one row per patient, worst tier).
    tier_of = {"urgent": "urgent", "high": "review", "medium": "review", "low": "info"}
    order = ["urgent", "review", "info"]
    counts = {"urgent": 0, "review": 0, "info": 0, "stable": 0}
    now = start + timedelta(days=DAYS - 1, hours=21)
    for p in data["patients"]:
        pid = p["id"]
        alerts = evaluate({"id": pid, "pregnant": p["pregnant"], "sex": p["sex"], "birth_year": p["birth_year"]},
                          by["seizures"][pid], by["intakes"][pid], by["reports"][pid], meds[pid], now, cfg)
        tiers = {tier_of[a["severity"]] for a in alerts}
        counts[next((t for t in order if t in tiers), "stable")] += 1
    n = len(data["patients"])
    lines += ["## Queue snapshot on the last day (flag rate)", "",
              "| tier | patients | share |", "|---|---|---|"]
    lines += [f"| {k} | {v} | {v / n:.1%} |" for k, v in counts.items()]
    lines += ["", f"Shown by default (urgent + needs review): {counts['urgent'] + counts['review']}/{n} = "
              f"{(counts['urgent'] + counts['review']) / n:.1%}.", ""]
    # F2: the optional low-threshold queue view ("Voir aussi les alertes à seuil bas"). Presentation only:
    # same engine test, max_p = trend.sensitive_view_max_p_value; no alert is created with it.
    from engine.alerts import trend_test
    sp = cfg["trend"]["sensitive_view_max_p_value"]
    lines += [f"## Low-threshold queue view (F2: p < {sp}, presentation only)", ""]
    def first_sensitive(pid, from_day):
        for day in range(from_day, DAYS):
            if trend_test(by["seizures"][pid], start + timedelta(days=day, hours=21), cfg, max_p=sp)[0]:
                return day
        return None
    default_missed = [p for p in rising if first_flag(data, p, "seizure_increase", max(truth[p]["onset_day"], FIRST_DAY), cfg, start, meds, by) is None]
    lines += ["Rising patients missed by the default trend alert, checked against the low-threshold view:", "",
              "| patient | onset day | first day in low-threshold view | days after onset | in the view on the last day |",
              "|---|---|---|---|---|"]
    for p in default_missed:
        d = first_sensitive(p, max(truth[p]["onset_day"], FIRST_DAY))
        last = trend_test(by["seizures"][p], now, cfg, max_p=sp)[0]
        lines.append(f"| {p} | {truth[p]['onset_day']} | {d if d is not None else 'never'} | "
                     f"{d - truth[p]['onset_day'] if d is not None else '—'} | {'yes' if last else 'no'} |")
    lines += ["", "A flag on the onset day itself (0 days) means the patient's count was already borderline before the "
              "injected rise started: the low-threshold view includes these patients, but partly by chance, not as "
              "proof that it detects the rise faster."]
    extra = {"rising": 0, "other": 0}
    extra_ids = []
    for p in data["patients"]:
        pid = p["id"]
        alerts = evaluate({"id": pid, "pregnant": p["pregnant"], "sex": p["sex"], "birth_year": p["birth_year"]},
                          by["seizures"][pid], by["intakes"][pid], by["reports"][pid], meds[pid], now, cfg)
        in_default = any(tier_of[a["severity"]] in ("urgent", "review") for a in alerts)
        if not in_default and trend_test(by["seizures"][pid], now, cfg, max_p=sp)[0]:
            extra["rising" if truth[pid]["archetype"] == "rising" else "other"] += 1
            extra_ids.append(pid)
    lines += ["", f"On the last day the low-threshold view adds **{len(extra_ids)}** patient(s) to the "
              f"{counts['urgent'] + counts['review']} in the default queue: {extra['rising']} with injected rising "
              f"seizures, {extra['other']} without (false alarms)."
              + (f" ({', '.join(extra_ids)})" if extra_ids else ""), ""]
    lines += ["Note: some rising/poor-adherence onsets fall before day 112; for those, detection is counted from day 112 "
              "and the delay is still measured from the true onset, so their delays are longer.", ""]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
