#!/usr/bin/env python3
"""Build docs/EVALUATION_SUMMARY.md (F9) by COPYING lines from the generated reports.

Numbers are never retyped or rounded here: every table is an excerpt of
  backend/reports/alert_evaluation.md   (python -m scripts.evaluate_alerts)
  backend/reports/ai_evaluation.md      (python -m scripts.evaluate_ai)
  load/RESULTS.md                       (k6 run, conditions included)
  git show 70aa454:backend/reports/alert_evaluation.md   (the "before" alert evaluation, rules-0.1.0)
Run from the repository root:  python3 scripts/eval_summary.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEFORE_COMMIT = "70aa454"


def section(text: str, heading: str) -> str:
    """Lines under the heading that starts with `heading`, up to the next heading of the same or higher level."""
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if re.match(r"#+ ", l) and l.lstrip("# ").startswith(heading))
    level = len(lines[start]) - len(lines[start].lstrip("#"))
    out = []
    for l in lines[start + 1:]:
        m = re.match(r"(#+) ", l)
        if m and len(m.group(1)) <= level:
            break
        out.append(l)
    return "\n".join(out).strip()


def table(text: str) -> str:
    return "\n".join(l for l in text.splitlines() if l.startswith("|"))


alerts = (ROOT / "backend/reports/alert_evaluation.md").read_text(encoding="utf-8")
ai = (ROOT / "backend/reports/ai_evaluation.md").read_text(encoding="utf-8")
load = (ROOT / "load/RESULTS.md").read_text(encoding="utf-8")
before = subprocess.run(["git", "show", f"{BEFORE_COMMIT}:backend/reports/alert_evaluation.md"], cwd=ROOT,
                        capture_output=True, text=True, check=True).stdout

classifier = section(ai, "Description classifier")
risk = section(ai, "Seizure-risk estimate")

doc = f"""# EVALUATION_SUMMARY — what the numbers say (and do not say)

Generated by `python3 scripts/eval_summary.py`: every table below is **copied** from a generated report
(sources named under each heading), not retyped. All data is synthetic or placeholder; nothing here is
clinical evidence.

## 1. Alert engine on injected deterioration — before and after

**The two runs use different synthetic populations, so the figures are not directly comparable.**
*Before* (rules-0.1.0, commit `{BEFORE_COMMIT}`): 150 patients, 50 % stable / 20 % rising / 15 % poor adherence / 15 % cluster,
trend rule "recent ≥ 2 × baseline and ≥ 3". *After* (rules-0.2.0, current): 70 / 12 / 10 / 8 %, trend rule = Poisson
significance p < 0.01. Both: seed 42, 182 days, engine replayed daily from day 112.

Before — trend on rising patients (source: `git show {BEFORE_COMMIT}:backend/reports/alert_evaluation.md`):

{table(section(before, "seizure_increase on `rising` patients"))}

After — trend on rising patients (source: `backend/reports/alert_evaluation.md`):

{section(alerts, "seizure_increase on `rising` patients")}

After — adherence drop:

{table(section(alerts, "adherence_drop on `poor_adherence` patients"))}

## 2. Calm queue versus sensitivity

The default queue is calmer but slower and misses patients; the trade-off is a clinical choice (TODO-verify).
Source: `backend/reports/alert_evaluation.md`.

{table(section(alerts, "Trend threshold trade-off"))}

Queue on the last day:

{section(alerts, "Queue snapshot on the last day")}

Optional low-threshold view (F2, presentation only, off by default):

{section(alerts, "Low-threshold queue view")}

## 3. 7-day risk model versus a simple 4-week seizure count

Source: `backend/reports/ai_evaluation.md`.

{risk}

**Plainly: the risk model does not demonstrably beat the simple 4-week seizure count.**

## 4. Darija / Arabic / French description classifier

Source: `backend/reports/ai_evaluation.md`. Training data is a 75-row **placeholder written by the AI assistant**,
not clinician-reviewed; per-class precision/recall, confusion matrix and subgroup results:

{classifier}

## 5. Load test

Source: `load/RESULTS.md` (conditions included).

{load.split(chr(10), 1)[1].strip()}

## What is NOT validated

- **Nothing is clinically validated.** All patients are synthetic; the classifier's text data is a placeholder.
- Every threshold, first-aid line, drug rule, the pregnancy age range and the risk bands are TODO-verify by a neurologist.
- The alert evaluation measures how well the engine finds patterns **we injected ourselves**; real deterioration is messier.
- The models' subgroup gaps reflect small synthetic samples, not real bias; real bias is unmeasured.
- Load figures come from one laptop, one run per configuration, not a production deployment.
- Legal items (INPDP authorization, consent wording, data-deletion scope vs hospital records, medical-device
  classification) are TODO-verify with counsel.
- Arabic and Darija wording is provisional, pending native-speaker review.
"""
(ROOT / "docs/EVALUATION_SUMMARY.md").write_text(doc, encoding="utf-8")
print(f"wrote docs/EVALUATION_SUMMARY.md ({len(doc.splitlines())} lines)")
